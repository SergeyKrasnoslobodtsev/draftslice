"""Общие типы массивов пайплайна очистки чертежей.

Пайплайн работает с четырьмя видами данных: растр в градациях серого или BGR, бинарная маска
штрихов, вещественные величины по ребрам графа и целочисленные индексы. Отдельные алиасы нужны
для того, чтобы сигнатуры функций читались без комментариев: по типу видно, приходит ли в функцию
картинка, маска или таблица величин, снятых с ребер скелета.

Все массивы обычные numpy-массивы. Класс cv2.UMat в пайплайне не применяется: скелетизация,
построение графа и расчет признаков идут через skimage, skan, sklearn и numpy-индексацию, которые
работают только с обычной памятью, поэтому перенос части операций на OpenCL дал бы лишние
преобразования на каждой границе.
"""

import numpy as np
import numpy.typing as npt

Mat = npt.NDArray[np.uint8]
"""Растр: BGR или одноканальная картинка."""

Mask = npt.NDArray[np.bool_]
"""Бинарная маска, True это чернила."""

Floats = npt.NDArray[np.float64]
"""Вещественные величины, снятые с пикселей, ребер или компонент."""

Ints = npt.NDArray[np.int64]
"""Целочисленные индексы и метки."""

Window = tuple[float, float, float, float]
"""Окно просмотра в пикселях: x_left, x_right, y_top, y_bottom."""
